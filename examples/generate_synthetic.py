"""Generate ideal RLC and coupled-inductor Touchstone data with NumPy only.

No imported measurement, process model or electromagnetic simulation is used.
The series branch uses Z=R+j*w*L; shunt capacitors use Y=j*w*C.
The coupled four-terminal model uses mutual impedance j*w*k*sqrt(Lp*Ls).
"""
from pathlib import Path
import numpy as np

def write(path, freq, s):
    n = s.shape[1]
    lines = ['! Synthetic ideal circuit; generated by generate_synthetic.py', '# Hz S RI R 50']
    for f, matrix in zip(freq, s):
        values = [f]
        for col in range(n):
            for row in range(n):
                values.extend([matrix[row,col].real, matrix[row,col].imag])
        lines.append(' '.join('%.16g' % v for v in values))
    Path(path).write_text('\n'.join(lines)+'\n', encoding='utf-8')

def rlc(freq):
    w = 2*np.pi*freq
    g = 1/(2.5+1j*w*1.8e-9)
    y = np.zeros((len(freq),2,2), complex)
    y[:,0,0] = y[:,1,1] = g + 1j*w*18e-15
    y[:,0,1] = y[:,1,0] = -g
    return np.linalg.solve(np.eye(2)+50*y, np.eye(2)-50*y)

def coupled(freq, lp=2e-9, ls=1.5e-9, rp=3., rs=2.):
    incidence = np.array([[1,0],[-1,0],[0,1],[0,-1]])
    y = np.empty((len(freq),4,4),complex)
    for i, f in enumerate(freq):
        w = 2*np.pi*f
        z = np.array([[rp+1j*w*lp, 1j*w*.55*np.sqrt(lp*ls)],
                      [1j*w*.55*np.sqrt(lp*ls), rs+1j*w*ls]])
        y[i] = incidence @ np.linalg.inv(z) @ incidence.T + np.eye(4)*1j*w*12e-15
    return np.linalg.solve(np.eye(4)+50*y, np.eye(4)-50*y)

def tapped(freq):
    # Two RL half-windings with independent skin-loss branches and shunt C.
    incidence = np.array([[1,0],[0,-1],[-1,1]])
    y = np.empty((len(freq),3,3),complex)
    for i, f in enumerate(freq):
        w=2*np.pi*f
        skin = (7*1j*w*.35e-9)/(7+1j*w*.35e-9)
        branch = 1/(1.5+1j*w*.85e-9+skin)
        y[i] = incidence @ np.diag([branch,branch]) @ incidence.T + np.eye(3)*1j*w*8e-15
    return np.linalg.solve(np.eye(3)+50*y,np.eye(3)-50*y)

